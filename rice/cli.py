def _select(args, comps) -> list[str]:
    st = state.load()
    ids = list(args.ids)
    if getattr(args, "defaults", False):
        ids += [c.id for c in comps if state.is_enabled(st, c.id) or (c.default and c.id not in st)]
    ids += [x for w in getattr(args, "with_", None) or [] for x in w.split(",") if x]
    drop = {x for w in getattr(args, "without", None) or [] for x in w.split(",") if x}
    known = {c.id for c in comps}
    bad = [i for i in ids if i not in known]
    if bad:
        sys.exit(f"unknown component(s): {', '.join(bad)}")
    return [i for i in dict.fromkeys(ids) if i not in drop]


def _print(results, dry, show_diff):
    n = 0
    for i, r in results.items():
        print(f"{i}: {r.status}" + (f" ({r.message})" if r.message else ""))
        n += len(r.changes)
        for ch in r.changes:
            print(f"  {ch.kind}: {ch.relpath}")
            if show_diff and ch.diff:
                print(ch.diff, end="" if ch.diff.endswith("\n") else "\n")
    if dry:
        print(f"{n} changes")
    return 1 if any(r.status == "failed" for r in results.values()) else 0


def _packages(a) -> int:
    sets = packages.load()
    if a.pcmd == "list":
        for s in sets:
            print(f"{s.id}\t{s.group}\t{int(s.default)}\t{s.step or '-'}\t{s.title}")
        return 0
    if a.pcmd == "status":
        for i, st in packages.status(sets).items():
            print(f"{i}: " + {"installed": "installed", "missing": "not installed"}.get(
                st.state, f"partial (missing: {' '.join(st.missing)})"))
        return 0
    bad = [i for i in a.ids if i not in {s.id for s in sets}]
    if bad:
        print("unknown set(s): " + ", ".join(bad), file=sys.stderr)
        return 2
    r = None
    if a.result:
        packages.write_result(a.result, {"state": "running", "pid": os.getpid()})
    try:
        try:
            r = (packages.install if a.pcmd == "install" else packages.remove)(a.ids)
        except Exception as e:
            r = packages.InstallResult(1, list(a.ids), f"{type(e).__name__}: {e}")
        if r.message:
            print(r.message)
        return r.rc
    finally:  # also on Ctrl-C: the GUI must never see a stale "running" record from a live pid
        if a.result:
            packages.write_result(a.result, r or packages.InstallResult(1, list(a.ids), "interrupted"))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="rice", description="Garuda Mokka for niri-noctalia-rice")
    sp = ap.add_subparsers(dest="cmd", required=True, metavar="{lock,fetch,apply,disable,status,update,owned,refresh,packages,gui}")
    p = sp.add_parser("lock", help="re-pin upstream sources from Garuda PKGBUILDs")
    g = p.add_mutually_exclusive_group(required=True)
    g.add_argument("--pkgbuilds", metavar="COMMIT")
    g.add_argument("--latest", action="store_true")
    p = sp.add_parser("fetch", help="download pinned sources")
    p.add_argument("ids", nargs="*")
    p.add_argument("--defaults", action="store_true")
    p = sp.add_parser("apply", help="apply components (--dry-run shows the diff)")
    p.add_argument("ids", nargs="*")
    p.add_argument("--defaults", action="store_true")
    p.add_argument("--with", dest="with_", action="append", metavar="a,b")
    p.add_argument("--without", action="append", metavar="a,b")
    p.add_argument("--variant", action="append", default=[], metavar="id=name")
    p.add_argument("--dry-run", action="store_true")
    p.add_argument("--force", action="store_true")
    p.add_argument("--install-needs", action="store_true", help="install missing package sets first")
    p.add_argument("--no-packages", action="store_true", help=argparse.SUPPRESS)  # deprecated no-op
    p.add_argument("--no-run", action="store_true")
    p.add_argument("--yes", action="store_true")
    p = sp.add_parser("disable", help="turn components off")
    p.add_argument("ids", nargs="+")
    p = sp.add_parser("status", help="show component state")
    p.add_argument("--remote", action="store_true")
    p = sp.add_parser("update", help="re-pin to latest and re-apply affected components")
    p.add_argument("--yes", action="store_true")
    sp.add_parser("owned", help="list paths owned by rice")
    p = sp.add_parser("refresh", help="restore the repo copy of an owned file")
    p.add_argument("relpath")
    p = sp.add_parser("packages", help="package sets: list|status|install|remove")
    pp = p.add_subparsers(dest="pcmd", required=True)
    pp.add_parser("list")
    pp.add_parser("status")
    for n in ("install", "remove"):
        q = pp.add_parser(n)
        q.add_argument("ids", nargs="+")
        q.add_argument("--result", metavar="F")
    p = sp.add_parser("gui", help="open the GTK4 GUI")
    p.add_argument("--smoke", action="store_true")
    a = ap.parse_args(argv)

    if a.cmd == "gui":
        from . import gui
        return gui.main(["--smoke"] if a.smoke else [])
    if a.cmd == "lock":
        for i, (o, n) in lock("latest" if a.latest else a.pkgbuilds).items():
            print(f"{i}: {(o or 'new')[:12]} -> {n[:12]}")
        return 0
    if a.cmd == "packages":
        return _packages(a)
    if a.cmd == "owned":
        print("\n".join(owned()))
        return 0
    if a.cmd == "refresh":
        return _print(refresh(a.relpath), False, False)
    if a.cmd == "update":
        return _print(update(a.yes)[1], False, False)
    if a.cmd == "status":
        for i, s in status(a.remote).items():
            flags = [f for f, on in (("needs-apply", s.needs_apply), ("not-built", s.needs_apply is None and s.enabled),
                                     ("recipe-changed", s.recipe_changed), ("app-missing", s.app_missing),
                                     ("update-available", s.update_available)) if on]
            flags += [f"stale:{x}" for x in s.stale_sources] + [f"edited:{x}" for x in s.modified]
            flags += [f"needs:{x}" for x in s.missing_needs] + (["run-pending"] if s.run_pending else [])
            print(f"{i}: {'on' if s.enabled else 'off'}" + (f" [{s.variant}]" if s.variant else "")
                  + (f"  {' '.join(flags)}" if flags else ""))
        return 0
    comps = components()
    ids = _select(a, comps)
    if a.cmd == "fetch":
        fetch(ids)
        return 0
    if a.cmd == "disable":
        return _print(disable(ids), False, False)
    variants = dict(v.split("=", 1) for v in a.variant)
    res = apply(ids, variants, a.dry_run, a.force, a.install_needs, not a.no_run)
    code = _print(res, a.dry_run, a.dry_run)
    named = list(a.ids) + [x for w in a.with_ or [] for x in w.split(",") if x]
    return int(code or any(res[i].status == "skipped" and res[i].message.startswith("needs ")
                           for i in named if i in res))
