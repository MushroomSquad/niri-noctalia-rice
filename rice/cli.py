@dataclass
class Result:
    status: str  # applied|unchanged|skipped|modified|failed
    changes: list = field(default_factory=list)
    message: str = ""


class _Skip(Exception):
    pass


def components() -> list[Component]:
    comps = [recipe.load(p) for p in sorted(COMPONENTS_DIR.glob("*.toml"))]
    for c in comps:
        _resolve_theme(c)
    return comps


def _resolve_theme(c) -> bool:
    """Rewrite c.theme_dir in the recipe to the dir name found on disk (case-insensitive); False if absent."""
    n = c.theme_dir
    if not n:
        return True
    roots = [Path("/usr/share/icons"), Path.home() / ".local/share/icons"]
    found = next((d.name for r in roots if r.is_dir() for d in r.iterdir()
                  if d.is_dir() and d.name.lower() == n.lower()), None)
    if found is None:
        return False
    if found != n:
        sub = lambda o: json.loads(json.dumps(o).replace(n, found))
        c.steps, c.off_steps, c.niri_snippet = sub(c.steps), sub(c.off_steps), sub(c.niri_snippet)
        for v in c.variants.values():
            v.steps = sub(v.steps)
        c.theme_dir = found
    return True


def _lock() -> dict:
    return tomllib.loads(lock_mod.LOCK_PATH.read_text())


def lock(pkgbuilds: str, write: bool = True) -> dict:
    return lock_mod.lock(pkgbuilds, write)


def source_path(lock_id: str) -> Path | None:
    """Cached source tree/file of a lock id, or None if not fetched (no network)."""
    try:
        return fetch_mod.path(lock_id, _lock()[lock_id])
    except (KeyError, OSError):
        return None


# ---------------------------------------------------------------- helpers

def _sources(c, variant, lk) -> list[str]:
    ids = {s.partition(":")[0] for s in c.sources}
    for s in recipe.all_steps(c, variant):
        for k in ("src", "target"):
            v = s.get(k)
            if isinstance(v, str) and ":" in v:
                ids.add(v.partition(":")[0])
    return sorted(i for i in ids if i in lk)


def _all_sources(c, lk) -> list[str]:
    return sorted({i for v in [None, *c.variants] for i in _sources(c, v, lk)})


def _installed(spec) -> bool:
    return any(shutil.which(n) for n in re.split(r"\s*(?:\||,|\bor\b)\s*", spec.strip()))


def _variant(c, st, variants):
    old = st.get(c.id, {})
    return (variants or {}).get(c.id) or (old.get("variant") if state.is_enabled(st, c.id) else None) or c.default_variant


def _unmet(c, variant, pst) -> list[str]:
    return [n for n in recipe.needs(c, variant) if n not in pst or pst[n].state != "installed"]


def _repo_digest(c, variant) -> str:
    h = hashlib.sha256()
    for s in recipe.all_steps(c, variant):
        if s["op"] == "copy" and s["src"].startswith("repo:"):
            base = REPO / s["src"][5:]
            for f in sorted([base] if base.is_file() else base.rglob("*")):
                if f.is_file():
                    h.update(f.relative_to(REPO).as_posix().encode() + f.read_bytes())
    return h.hexdigest()


def _render(c, variant, lk, home, dry):
    """-> {relpath: (path, track)} from the build cache (rendering on a miss), or None (not built yet)."""
    srcs = {}
    for i in _sources(c, variant, lk):
        p = fetch_mod.path(i, lk[i])
        if p is None and not dry:
            p = fetch_mod.ensure(i, lk[i])
        if p is None:
            return None
        srcs[i] = p
    key = hashlib.sha256(json.dumps([{i: lk[i]["ref"] for i in srcs}, recipe.recipe_hash(c, variant), variant,
                                     str(home), _repo_digest(c, variant)]).encode()).hexdigest()
    bdir = fetch_mod.cache_root() / "build" / c.id
    meta = bdir.with_name(c.id + ".meta.json")
    try:
        m = json.loads(meta.read_text())
        if m["key"] == key and bdir.is_dir():
            return {r: (bdir / r, t) for r, t in m["files"].items()}
    except (OSError, ValueError, KeyError):
        pass
    if dry and any(s["op"] == "run" and s.get("when", "apply") == "build" for s in recipe.all_steps(c, variant)):
        return None
    shutil.rmtree(bdir, ignore_errors=True)
    whole = recipe.render_whole(c, variant, srcs, REPO, bdir, GENERATORS)
    meta.write_text(json.dumps({"key": key, "files": {r: t for r, (_, t) in whole.items()}}))
    return whole


def _read_live(rel, home, overlay) -> str:
    if rel in overlay:
        return overlay[rel]
    for p in (Path(home) / rel, REPO / "home" / rel):
        if p.is_file():
            return p.read_text()
    return ""


def _getkey(text, op):
    try:
        d = tomllib.loads(text) if op["op"] == "toml_set" else json.loads(text)
        for k in op["key"].split("."):
            d = d[k]
        return d
    except (KeyError, TypeError, ValueError):
        return None


def _patch_all(ops_by_target, home, ts, dry, overlay, prev=None) -> list[Change]:
    out = []
    for t, ops in ops_by_target.items():
        text = new = _read_live(t, home, overlay)
        for op in ops:
            pk = f"{t}:{op.get('key')}"
            if prev and pk in prev and op["op"] in PATCH_RUN_KINDS and not isinstance(op["value"], dict):
                op = dict(op, value=prev[pk])
            new = recipe.patch(new, op, home)
        if dry:
            overlay[t] = new
        ch = state.write_patched(t, new, home, ts, dry_run=dry)
        if ch:
            out.append(ch)
    return out


def _noctalia(*args):
    """`noctalia msg ...` -> (returncode, stdout, stderr); a missing binary is rc 127."""
    try:
        r = subprocess.run(["noctalia", "msg", *args], capture_output=True, text=True)
    except OSError as e:
        return 127, "", str(e)
    return r.returncode, r.stdout, r.stderr


def _noctalia_step(s) -> bool:
    """Read first, write only if different (a set pins the key in Noctalia's settings.toml)."""
    if "color_scheme" in s:
        rc, out, _ = _noctalia("color-scheme-get")
        if rc:
            return False
        want = s["color_scheme"]
        return out.strip() == " ".join(want) or _noctalia("color-scheme-set", *want)[0] == 0
    path = s.get("list_add") or s["list_remove"]
    rc, out, err = _noctalia("config-get", path)
    try:
        if rc == 0:
            cur = tomllib.loads("v = " + out)["v"]
        elif "path not found" in out + err:
            cur = []
        else:
            return False
    except (ValueError, KeyError):
        return False
    new = recipe._new_toml_value(cur, {"add" if "list_add" in s else "remove": s["item"]})
    return new == cur or _noctalia("config-set", path, recipe._fmt(new))[0] == 0


def _label(s) -> str:
    if "argv" in s:
        return " ".join(s["argv"])
    return "noctalia " + " ".join(f"{k}={v}" for k, v in s.items() if k != "op")


def _noctalia_prev(steps, home, overlay) -> dict:
    """Pre-change values of what noctalia steps touch, from files (settings.toml overrides config.toml)."""
    layers = []
    base = os.environ.get("XDG_STATE_HOME") or str(Path(home) / ".local/state")
    for text in (_read_noctalia_settings(base), _read_live(NOCTALIA_CFG, home, overlay)):
        try:
            layers.append(tomllib.loads(text))
        except ValueError:
            pass

    def get(path):
        for d in layers:
            try:
                for k in path.split("."):
                    d = d[k]
                return d
            except (KeyError, TypeError):
                pass

    out = {}
    for s in steps:
        if s["op"] != "noctalia":
            continue
        if "color_scheme" in s:
            src = get("theme.source")
            name = get("theme." + {"custom": "custom_palette", "builtin": "builtin"}.get(src, "-"))
            if src and name:
                out["noctalia:color_scheme"] = [src, name]
        else:
            path = s.get("list_add") or s["list_remove"]
            out[f"noctalia:list:{path}:{s['item']}"] = s["item"] in (get(path) or [])
    return out


def _read_noctalia_settings(base) -> str:
    try:
        return (Path(base) / "noctalia" / "settings.toml").read_text()
    except OSError:
        return ""


def _run_steps(steps, home, log) -> bool:
    ok, reloaded = True, False
    for s in steps:
        log(("run: " if "argv" in s else "") + _label(s))
        if s.get("op") == "noctalia":
            if not reloaded:
                reloaded = True
                if _noctalia("config-reload")[0]:
                    return False
            ok &= _noctalia_step(s)
            continue
        try:
            argv = [a.replace("{repo}", str(REPO)) for a in s["argv"]]
            ok &= subprocess.run(argv, cwd=home).returncode == 0
        except OSError as e:
            log(f"run failed: {e}")
            ok = False
    return ok


def _process(c, st, lk, home, ts, variant, dry, force, pst, run, log, overlay):
    """-> (Result, needs_apply, new state entry|None)."""
    old = st.get(c.id, {})
    enabled = state.is_enabled(st, c.id)
    if c.only_if_installed and not _installed(c.only_if_installed):
        return Result("skipped", message=f"{c.only_if_installed} not installed"), False, None
    variant = variant or (old.get("variant") if enabled else None) or c.default_variant
    if variant and variant not in c.variants:
        raise ValueError(f"unknown variant {variant!r}")
    unmet = _unmet(c, variant, pst)
    if unmet:
        return Result("skipped", message="needs " + ", ".join(unmet)), False, None
    if not _resolve_theme(c):
        if not dry:
            raise RuntimeError("cursor theme dir not found")
        return Result("skipped", message=f"theme dir {c.theme_dir} not found"), False, None
    whole = _render(c, variant, lk, home, dry)
    if whole is None:
        return Result("skipped", message="not built yet (fetch/apply first)"), None, None
    rh = recipe.recipe_hash(c, variant)
    refs = {i: lk[i]["ref"] for i in _sources(c, variant, lk)}
    ops = recipe.patch_ops(c, variant)
    live = {t: o for t, o in ops.items() if t not in whole and not (":" in t and t.partition(":")[0] in lk)}
    prev = dict(old.get("prev", {})) if enabled else {}
    if not enabled:
        for op in c.off_steps or []:
            if op["op"] in PATCH_RUN_KINDS and not isinstance(op["value"], dict):
                v = _getkey(_read_live(op["target"], home, overlay), op)
                if v is not None:
                    prev[f"{op['target']}:{op['key']}"] = v
    steps = recipe.all_steps(c, variant)
    for k, v in _noctalia_prev(steps, home, overlay).items():
        prev.setdefault(k, v)
    recorded = old.get("whole", {})
    inst = state.install_whole(whole, home, recorded, ts, force=force,
                               reseed=old.get("variant") != variant, dry_run=dry)
    mod = {ch.relpath for ch in inst if ch.kind == "modified"}
    file_changes = [ch for ch in inst if ch.kind != "modified"] + _patch_all(live, home, ts, dry, overlay)
    changes = [ch for ch in inst if ch.kind == "modified"] + file_changes
    runs = [s for s in steps if s["op"] == "noctalia" or s["op"] == "run" and s.get("when", "apply") == "apply"]
    trig = bool(runs) and (not enabled or old.get("variant") != variant or old.get("recipe_hash") != rh
                           or old.get("refs") != refs or bool(file_changes) or bool(old.get("run_pending")))
    pending, ok = False, True
    if trig and run:
        if dry:
            changes += [Change(_label(s), "run") for s in runs]
        else:
            ok = _run_steps(runs, home, log)
            pending = not ok
    elif trig:
        pending = True
    entry = {"variant": variant, "refs": refs, "recipe_hash": rh,
             "whole": {r: (recorded.get(r) if r in mod else state.sha256(p)) for r, (p, t) in whole.items() if t},
             "seeded": sorted(r for r, (_, t) in whole.items() if not t), "patched": sorted(live),
             "prev": prev, "run_pending": pending}
    entry["whole"] = {r: s for r, s in entry["whole"].items() if s}
    needs = bool(changes) or bool(old.get("run_pending"))
    status = "failed" if not ok else "modified" if mod else "applied" if changes else "unchanged"
    msg = "run step failed, will retry" if not ok else ("hand-edited, use --force: " + ", ".join(sorted(mod)) if mod else "")
    return Result(status, changes, msg), needs, entry


def _kdl(comps, on) -> str:
    return KDL_HEADER + "".join(c.niri_snippet.strip() + "\n" for c in comps if c.id in on and c.niri_snippet)


def _sync_kdl(comps, st, results, extra, home, ts, dry):
    on = {i for i in st if state.is_enabled(st, i)} | extra
    if not on:
        return
    ch = state.write_patched(state.RICE_KDL, _kdl(comps, on), home, ts, dry_run=dry)
    if ch:
        for c in comps:
            if c.id in results and c.niri_snippet and results[c.id].status not in ("skipped", "failed"):
                results[c.id].changes.append(ch)
                if results[c.id].status == "unchanged":
                    results[c.id].status = "applied"
                break


def _seed_custom(home):
    """Seed missing user examples without ownership, state entries, or backups."""
    dest = Path(home) / ".config/rice-custom"
    dest.mkdir(parents=True, exist_ok=True)
    for src in sorted((REPO / "mokka/custom-skel").rglob("*")):
        if not src.is_file():
            continue
        target = dest / src.relative_to(REPO / "mokka/custom-skel")
        target.parent.mkdir(parents=True, exist_ok=True)
        try:
            with target.open("xb") as out:
                out.write(src.read_bytes())
        except FileExistsError:
            pass


def _apply(ids, variants, dry_run, force, install_needs, run, log, pst=None):
    lk, st, home, ts = _lock(), state.load(), Path.home(), time.strftime("%Y%m%d-%H%M%S")
    comps = components()
    if not dry_run:
        _seed_custom(home)
    results, needs, overlay = {}, {}, {}
    for i in ids:
        if i not in {c.id for c in comps}:
            results[i] = Result("failed", message=f"unknown component {i}")
    sel = [c for c in comps if c.id in ids]
    if pst is None:
        pst = packages.status() if any(c.needs or c.variants for c in sel) else {}
        absent = {n for c in sel if not (c.only_if_installed and not _installed(c.only_if_installed))
                  for n in _unmet(c, _variant(c, st, variants), pst)}
        if install_needs and absent and not dry_run:
            r = packages.install(sorted(absent), log=log)
            if r.message:
                log(r.message)
            pst = packages.status()
    for c in sel:
        try:
            res, needs[c.id], entry = _process(c, st, lk, home, ts, variants and variants.get(c.id), dry_run, force,
                                               pst, run, log, overlay)
            if entry and not dry_run:
                st[c.id] = entry
                state.save(st)
        except _Skip as e:
            res, needs[c.id] = Result("skipped", message=str(e)), False
        except Exception as e:  # a failed component must not stop the rest
            res, needs[c.id] = Result("failed", message=f"{type(e).__name__}: {e}"), False
        results[c.id] = res
    ok = {k for k, v in results.items() if k in needs and v.status not in ("skipped", "failed")}
    _sync_kdl(comps, st, results, ok, home, ts, dry_run)
    return results, needs


def apply(ids, variants=None, dry_run=False, force=False, install_needs=False, run=True,
          log=print) -> dict[str, Result]:
    return _apply(ids, variants, dry_run, force, install_needs, run, log)[0]


def fetch(ids: list[str]) -> None:
    lk = _lock()
    for c in components():
        if c.id in ids:
            for i in _all_sources(c, lk):
                fetch_mod.ensure(i, lk[i])


def disable(ids, log=print) -> dict[str, Result]:
    lk, st, home, ts = _lock(), state.load(), Path.home(), time.strftime("%Y%m%d-%H%M%S")
    comps = components()
    results = {i: Result("failed", message=f"unknown component {i}") for i in ids if i not in {c.id for c in comps}}
    for c in comps:
        if c.id not in ids:
            continue
        if not state.is_enabled(st, c.id):
            results[c.id] = Result("unchanged", message="not enabled")
            continue
        e = st[c.id]
        try:
            prev = e.get("prev", {})
            noct = []
            for s in c.off_steps or []:
                if s["op"] != "noctalia":
                    continue
                if "color_scheme" in s:
                    s = dict(s, color_scheme=prev.get("noctalia:color_scheme", s["color_scheme"]))
                else:  # undo only what rice changed: removals if absent before, re-adds if present before
                    was = prev.get(f"noctalia:list:{s.get('list_add') or s['list_remove']}:{s['item']}")
                    if was is not None and was != ("list_add" in s):
                        continue
                noct.append(s)
            if noct and not _run_steps(noct, home, log):
                results[c.id] = Result("failed", message="Noctalia not running; start it and retry")
                continue
            off = [s for s in c.off_steps or [] if s["op"] in recipe.PATCH_OPS]
            ops: dict = {}
            for s in off:
                ops.setdefault(s["target"], []).append(s)
            changes = _patch_all(ops, home, ts, False, {}, e.get("prev"))
            ok = _run_steps([s for s in c.off_steps or [] if s["op"] == "run"], home, log)
            e["patched"] = sorted(set(e.get("patched", [])) | set(ops))
            st[c.id] = state.disabled_entry(e)
            state.save(st)
            results[c.id] = Result("applied" if ok else "failed", changes, "" if ok else "off run step failed")
        except Exception as ex:
            results[c.id] = Result("failed", message=f"{type(ex).__name__}: {ex}")
    _sync_kdl(comps, st, results, set(), home, ts, False)
    return results


def status(remote=False) -> dict[str, Status]:
    lk, st, home = _lock(), state.load(), Path.home()
    moved = {}
    if remote:
        try:
            moved = lock_mod.lock("latest", write=False)
        except Exception:
            moved = {}
    comps = components()
    pst = packages.status()
    _, needs = _apply([c.id for c in comps if state.is_enabled(st, c.id)], None, True, False, False, True,
                      lambda *_: None, pst)
    out = {}
    for c in comps:
        e = st.get(c.id, {})
        on = state.is_enabled(st, c.id)
        v = e.get("variant") if on else c.default_variant
        s = Status(enabled=on, variant=e.get("variant") if on else None, needs_apply=needs.get(c.id, False))
        s.app_missing = bool(c.only_if_installed) and not _installed(c.only_if_installed)
        s.missing_needs = _unmet(c, v, pst)
        s.run_pending = bool(e.get("run_pending")) and on
        if remote:
            s.update_available = any(i in moved for i in _all_sources(c, lk))
        if on:
            s.stale_sources = [i for i in _sources(c, v, lk) if e.get("refs", {}).get(i) != lk[i]["ref"]]
            s.recipe_changed = e.get("recipe_hash") != recipe.recipe_hash(c, v)
            s.modified = [r for r, sha in e.get("whole", {}).items()
                          if (home / r).is_file() and state.sha256(home / r) != sha]
            if e.get("run_pending"):
                s.needs_apply = True
        out[c.id] = s
    return out


def update(yes=False, log=print):
    moved = lock_mod.lock("latest", write=yes)
    for i, (o, n) in moved.items():
        log(f"{i}: {(o or 'new')[:12]} -> {n[:12]}")
    if not yes:
        log("run with --yes to write the lock, fetch and apply" if moved else "up to date")
        return moved, {}
    lk, st = _lock(), state.load()
    affected = [c.id for c in components()
                if state.is_enabled(st, c.id) and set(_all_sources(c, lk)) & set(moved)]
    return moved, apply(affected, log=log) if affected else {}


def owned() -> list[str]:
    return state.owned(state.load())


def refresh(relpath, log=print) -> dict[str, Result]:
    home, ts, st = Path.home(), time.strftime("%Y%m%d-%H%M%S"), state.load()
    src = REPO / "home" / relpath
    if not src.is_file():
        return {relpath: Result("failed", message=f"no repo copy home/{relpath}")}
    text = src.read_text()
    for c in components():
        if state.is_enabled(st, c.id):
            for op in recipe.patch_ops(c, st[c.id].get("variant")).get(relpath, []):
                text = recipe.patch(text, op, home)
    ch = state.write_patched(relpath, text, home, ts)
    return {relpath: Result("applied" if ch else "unchanged", [ch] if ch else [])}


